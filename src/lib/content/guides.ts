/**
 * ルールと制度の解説（`/guide` と `/guide/<slug>`）。**手で書く編集コンテンツ。**
 *
 * ------------------------------------------------------------------
 * ★★ なぜ作ったか（2026-09-21）
 *
 *   運営者がくれたキーワードプランナーの実測で、高校野球に固有のルール語が
 *   夏に大きな山を持っていた（「高校野球 コールド」7月33,100、「球数制限」8月18,100、
 *   「タイブレーク」8月9,900）。一般的な野球のルール解説は需要が小さく主題からも
 *   離れるので見送り、**高校野球・地方大会・公立に固有のルールと制度だけ**を書く。
 *
 * ------------------------------------------------------------------
 * ★★★ 書き方の決めごと
 *
 *   - **規則の中身は日本高野連の一次資料に基づく**（高校野球特別規則・大会要項・お知らせ）。
 *     歴史や経緯で一次資料に無いものは ja.wikipedia を出典として明記する。
 *     **出典に無いことは書かない。** 推測で埋めない。
 *   - **各ページに「基づく規則の年度」と「最終確認日」を置く。** 規則は毎年変わる
 *     （タイブレークの開始回・継続試合・低反発バット・指名打者はどれもここ数年の変更）。
 *     **高野連が年明けに特別規則を改正したら、年に一度ここを見直すこと。**
 *   - **数字の裏づけは描画時に生成物から数える**（`src/lib/guide-data.ts`）。
 *     ここに数字を書き写さない（データが増えた瞬間に嘘になる）。
 *   - **「0勝」「敗戦数」を出さない・選手個人の記録を作らない**は、ほかのページと同じ。
 *   - slug はローマ字（AGENTS.md）。
 *
 * ★ 背番号の意味（1番が投手、10番以降が控え、など）は**慣行であって規則ではなく、
 *   一次資料が無い**ので書いていない（2026-09-21 に見送り）。
 */

