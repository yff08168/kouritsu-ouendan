/**
 * 甲子園の大会記事に出てくる**公立校のうち、学校ページに結び付けられないもの**
 * （手で書く。人が Wikipedia の学校の記事を読んで確かめた）。
 *
 * ------------------------------------------------------------------
 * ★★ なぜ別に持つのか（2026-11-04）
 *
 *   `getSchoolNameIndex` は大会記事の校名を学校マスタ（**現存校だけ**）に結び付けて
 *   「公立」と数える。閉校した公立校はマスタに行が無いので数えられず、
 *   1991年春ベスト4の市川（山梨）・1968年春優勝の大宮工（埼玉）・1948年春準優勝の京都二商が
 *   **公立の優勝・準優勝・ベスト4に入っていなかった**。
 *
 *   別名表（`src/lib/data/koshien-school-aliases.json`）は、Wikipedia の表のリンク先が
 *   マスタの学校に結び付くものを機械的に作る。ここに載せるのは、**それでは結び付かない**
 *   次の2種類だけ。
 *
 *     ・マスタに行が無い閉校校で、**DB（`school_championships`）が承継先を持っていない**もの
 *       （`data/school-successor.json` が「要確認」のまま）
 *     ・大会記事の表にリンクが無く、機械では学校記事に結び付けられないもの
 *
 * ------------------------------------------------------------------
 * ★★ 学校ページには結び付けない（`slug` は null）。**公立として数えて、リンクだけ張らない。**
 *
 *   承継先の学校（青洲・大宮科学技術 など）が学校マスタにあっても、ここでは結ばない。
 *   ★**学校ページの出場歴は DB（`school_championships`）から来る**ので、DB が承継先に出場歴を
 *   付けていないのに大会ページだけ結ぶと、**リンク先に載っていない出場へ案内する**ことになる。
 *   ★**結ぶなら先に `data/school-successor.json` の `confirmed` を埋め、`koshien.sql` を作り直して
 *   人が流す**（そうすれば別名表の生成が自動で結んでくれる。README「甲子園の公立判定の穴」）。
 *
 * ★★ 足す前に必ず Wikipedia の学校の記事の **wikitext を読む**
 *   （`node scripts/fetch-wikipedia-pages.mjs "<記事名>"`。要約モデルに通さない）。
 *   見るのは ①`国公私立`・`設置者`（公立か）②`閉校年月日`・本文（閉校・統合）③甲子園に出た記述。
 *   ★**校名から公立と決めない。** 2026-11-04 に、READMEの候補表にあった「帯広北」を読んだら
 *   **私立（学校法人帯広渡辺学園）**だった。愛知の弥富（愛知黎明）も私立。
 *   ★**確かめられないものは足さない。**
 *
 * ★ `display` は大会記事の校名（`koshien-games.json` の `display`）と同じ字で書く。
 *   県の書かれていない古い大会の試合は `prefless: true`（県なしの照合にも使う）。
 */

export type UnlinkedPublicSchool = {
  /** 大会記事（甲子園）での校名 */
  display: string;
  /** 県。甲子園の大会区分でよい（北北海道は北海道に寄せて照合する） */
  pref: string;
  /** 試合に県が書かれていない（古い大会）。県なしの照合にも使う */
  prefless?: boolean;
  /** 正式名称（Wikipedia の記事名） */
  official: string;
  /** 画面に出す一言（閉校・統合の事実）。現存校なら省く */
  status?: string;
  /** 確かめた記事と箇所（コードの読み手向け。画面には出さない） */
  source: string;
};

