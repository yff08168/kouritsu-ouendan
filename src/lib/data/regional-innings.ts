/**
 * 地方大会の**各回の得点**（生成物）。`scripts/build-regional-innings.mjs` が書く。
 *
 * ------------------------------------------------------------------
 * ★★★**なぜ県のファイルの外にあるか**（2026-09-07）
 *
 * **中に持たせていたら、結果を取り直すワークフローに1,510試合ぶんを一度に消された。**
 * 結果は1日2回、出典から読み直して県のファイルを**丸ごと書き直す**ので、
 * **開催中の大会の試合は毎回新しいオブジェクトになる** ——
 * **そこに足したものは必ず消える。**
 * ★**警告もエラーも出ない。** 試合数はむしろ増えるので、数だけ見ていると気づけない。
 *
 * ★**取り込みは別の出典（HSB flash）・別のスクリプト・別の周期**なのだから、
 * **置き場所も分ける。** こうしておけば、結果を何度取り直しても消えない。
 *
 * ------------------------------------------------------------------
 * ★**鍵は `gameSeed`**（`src/lib/regional-results.ts`）——
 * 日付・回戦・両校名・得点をつないだ文字列。
 * ★**スコアが直れば鍵も変わる**ので、古い各回が別の試合に付くことはない。
 * ★**ハッシュにしていないのは、スクリプト側と同じ結果になることを目で確かめられるようにするため。**
 *
 * ★**`from` は「県の出典と違う出所から取った」ときだけ入る**
 * （スコアは連盟・各回は速報、という試合）。**画面には出していない**が、
 * どこから来たかの記録は残す。
 */
import table from "./regional-innings.json";

export type RegionalInnings = Record<
  string,
  Record<string, { innings: number[][]; from?: string }>
>;

