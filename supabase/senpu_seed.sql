-- ⚠️ 管理画面から本文を手で直せるようにしたら、この do update は見直すこと。
-- 手の修正を消してしまう。
on conflict (slug) do update set
  title   = excluded.title,
  summary = excluded.summary,
  body    = excluded.body,
  badge   = excluded.badge;


-- ------------------------------------------------------------
-- 記録 ⇄ 学校のひもづけ
--
-- slug で引いて入れる。学校が未登録なら何も入らない（エラーにはしない）。
-- 対戦相手（role='opponent'）はここでは入れていない。私学を「破られた相手」
-- として一覧に並べるのは、このサイトの立ち位置として避けたいため。
-- ------------------------------------------------------------
insert into public.phenomenon_schools (phenomenon_id, school_id, role)
select p.id, s.id, 'main'
from (values
  ('gifushogyo-2025-summer',   'gifushogyo'),
  ('taisha-2024-summer',       'taisha'),
  ('kanaashinogyo-2018-summer','kanaashinogyo'),
  ('sagakita-2007-summer',     'sagakita')
) as v (phenomenon_slug, school_slug)
join public.phenomena p on p.slug = v.phenomenon_slug
join public.schools    s on s.slug = v.school_slug
on conflict (phenomenon_id, school_id) do nothing;

commit;


-- 確認用。4行が返り、ひもづけ学校数がどれも1なら成功。
select ph.slug,
       ph.year,
       ph.badge,
       count(ps.school_id) as linked_schools
from public.phenomena ph
left join public.phenomenon_schools ps on ps.phenomenon_id = ph.id
where ph.slug in ('gifushogyo-2025-summer', 'taisha-2024-summer',
                  'kanaashinogyo-2018-summer', 'sagakita-2007-summer')
group by ph.slug, ph.year, ph.badge
order by ph.year desc;
